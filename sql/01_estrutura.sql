CREATE TABLE CLIENTE (
    ID INTEGER NOT NULL PRIMARY KEY,
    COD_PORTAL INTEGER NOT NULL UNIQUE,
    NOME VARCHAR(100) NOT NULL
);

CREATE TABLE PRODUTO (
    ID INTEGER NOT NULL PRIMARY KEY,
    COD_PORTAL INTEGER NOT NULL UNIQUE,
    DESCRICAO VARCHAR(120) NOT NULL
);

CREATE TABLE ESTOQUE (
    PRODUTO_ID INTEGER NOT NULL PRIMARY KEY REFERENCES PRODUTO (ID),
    QTD_FISICA INTEGER NOT NULL,
    QTD_RESERVADA INTEGER NOT NULL,
    CHECK (QTD_RESERVADA >= 0 AND QTD_FISICA >= QTD_RESERVADA)
);

CREATE TABLE PEDIDO (
    ID INTEGER NOT NULL PRIMARY KEY,
    COD_PORTAL INTEGER NOT NULL UNIQUE,
    CLIENTE_ID INTEGER NOT NULL REFERENCES CLIENTE (ID),
    DATA_IMPORTACAO TIMESTAMP NOT NULL,
    TOTAL_LIQUIDO NUMERIC(15,2) NOT NULL
);

CREATE TABLE PEDIDO_ITEM (
    PEDIDO_ID INTEGER NOT NULL REFERENCES PEDIDO (ID),
    SEQUENCIA INTEGER NOT NULL CHECK (SEQUENCIA > 0),
    PRODUTO_ID INTEGER NOT NULL REFERENCES PRODUTO (ID),
    QUANTIDADE INTEGER NOT NULL CHECK (QUANTIDADE > 0),
    PRECO_UNITARIO NUMERIC(15,2) NOT NULL,
    TOTAL_LIQUIDO NUMERIC(15,2) NOT NULL,
    PRIMARY KEY (PEDIDO_ID, SEQUENCIA)
);

CREATE TABLE IMPORTACAO_TENTATIVA (
    ID INTEGER NOT NULL PRIMARY KEY,
    COD_PEDIDO_PORTAL INTEGER NOT NULL,
    INICIO TIMESTAMP NOT NULL,
    FIM TIMESTAMP,
    STATUS VARCHAR(24) NOT NULL,
    MENSAGEM VARCHAR(500),
    TENTATIVA_ORIGEM_ID INTEGER REFERENCES IMPORTACAO_TENTATIVA (ID),
    CHECK (STATUS IN ('EM_ANDAMENTO', 'IMPORTADO', 'JA_IMPORTADO',
        'NAO_ENCONTRADO', 'FALHA_AUTENTICACAO', 'FALHA_API',
        'REJEITADO_CADASTRO', 'ESTOQUE_INSUFICIENTE', 'FALHA_GRAVACAO')),
    CHECK (STATUS = 'EM_ANDAMENTO' OR (FIM IS NOT NULL AND MENSAGEM IS NOT NULL))
);

CREATE TABLE MOVIMENTO_ESTOQUE (
    ID INTEGER NOT NULL PRIMARY KEY,
    PRODUTO_ID INTEGER NOT NULL REFERENCES PRODUTO (ID),
    DATA_HORA TIMESTAMP NOT NULL,
    TIPO VARCHAR(7) NOT NULL CHECK (TIPO IN ('ENTRADA', 'SAIDA')),
    QUANTIDADE INTEGER NOT NULL CHECK (QUANTIDADE > 0),
    MOTIVO VARCHAR(200) NOT NULL,
    FISICO_ANTERIOR INTEGER NOT NULL,
    FISICO_POSTERIOR INTEGER NOT NULL
);

CREATE GENERATOR GEN_PEDIDO;
CREATE GENERATOR GEN_TENTATIVA;
CREATE GENERATOR GEN_MOVIMENTO;
